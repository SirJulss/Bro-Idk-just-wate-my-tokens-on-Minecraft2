//! Texture definitions: where the pixels of a material come from.
//!
//! A texture is either *procedural* (the name of a `cp-proctex` recipe plus parameters and a
//! seed) or an image *file* inside the pack. This crate only describes textures; the
//! application generates or loads the pixels. It does not depend on `cp-proctex`, so recipe
//! names and parameters are carried as plain data ([`Params`]) in the text form that
//! `cp-proctex` reads, and are checked against the recipes by the tool that has both crates
//! (`cpe content-check`).

use core::fmt;
use std::collections::BTreeMap;
use std::path::PathBuf;

use serde::Deserialize;
use serde::de::{self, Deserializer, Visitor};

/// Who made a texture. Release builds must contain own art only.
#[derive(Clone, Copy, PartialEq, Eq, Hash, Debug, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Provenance {
    /// Made for this project; safe to ship.
    Own,
    /// Third-party art standing in until own art exists; must not ship. Needs a `licence`.
    Placeholder,
}

/// Where the pixels of a texture come from.
#[derive(Clone, Debug, PartialEq, Eq)]
pub enum TextureSource {
    /// Generated by a `cp-proctex` recipe.
    Procedural {
        /// Name of the recipe, e.g. `"stone"` or `"log_side"`.
        recipe: String,
        /// Colours and variants for the recipe; empty for the recipe's defaults.
        params: Params,
        /// Seed of the recipe's random numbers.
        seed: u64,
    },
    /// Loaded from an image file of the pack.
    File {
        /// The path as written in the pack: relative to the pack directory, `/`-separated.
        path: String,
        /// The same file below the pack directory it was declared in; open this one.
        resolved: PathBuf,
    },
}

/// A texture as defined by a content pack.
///
/// Obtained from [`Registry::textures`](crate::Registry::textures), where the index of a
/// texture is its [`TextureLayer`](cp_core::ids::TextureLayer).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct TextureDef {
    /// The texture's key, `namespace:name`.
    pub key: String,
    /// Where the pixels come from.
    pub source: TextureSource,
    /// Who made it.
    pub provenance: Provenance,
    /// Licence of the art. Always present for [`Provenance::Placeholder`].
    pub licence: Option<String>,
}

/// One parameter of a procedural texture: a colour or the name of a variant
/// (contract §4.3: "`Params` carries colours/variants").
///
/// In TOML a parameter is a string. A string that starts with `#` is a colour and must have
/// the form `#rrggbb` or `#rgb` (hexadecimal, either case; `#f80` means `#ff8800`). Any other
/// string names a variant, for example a bark style.
#[derive(Clone, Debug, PartialEq, Eq, Hash)]
pub enum ParamValue {
    /// An sRGB colour `[red, green, blue]`.
    Color([u8; 3]),
    /// The name of a structural variant of the recipe.
    Variant(String),
}

impl ParamValue {
    /// Reads a parameter from its text form; `None` for text that starts with `#` but is not
    /// a colour.
    fn parse(text: &str) -> Option<Self> {
        let Some(digits) = text.strip_prefix('#') else {
            return Some(Self::Variant(text.to_owned()));
        };
        if digits.len() != 3 && digits.len() != 6 {
            return None;
        }
        // Hexadecimal digits are ASCII: every byte must be one, so a multi-byte character
        // never passes.
        let mut nibbles = [0_u8; 6];
        for (nibble, byte) in nibbles.iter_mut().zip(digits.bytes()) {
            *nibble = u8::try_from(char::from(byte).to_digit(16)?).ok()?;
        }
        let [a, b, c, d, e, f] = nibbles;
        Some(Self::Color(if digits.len() == 3 {
            // `#rgb` doubles every digit: 0xf becomes 0xff.
            [a * 17, b * 17, c * 17]
        } else {
            [(a << 4) | b, (c << 4) | d, (e << 4) | f]
        }))
    }
}

/// The parameters of a procedural texture: values by name, iterated in name order.
#[derive(Clone, Debug, Default, PartialEq, Eq, Deserialize)]
#[serde(transparent)]
pub struct Params(BTreeMap<String, ParamValue>);

impl Params {
    /// The parameter `name`, if given.
    #[must_use]
    pub fn get(&self, name: &str) -> Option<&ParamValue> {
        self.0.get(name)
    }

    /// The colour parameter `name` as sRGB bytes; `None` when absent or not a colour.
    #[must_use]
    pub fn color(&self, name: &str) -> Option<[u8; 3]> {
        match self.get(name)? {
            ParamValue::Color(color) => Some(*color),
            ParamValue::Variant(_) => None,
        }
    }

    /// The variant parameter `name`; `None` when absent or a colour.
    #[must_use]
    pub fn variant(&self, name: &str) -> Option<&str> {
        match self.get(name)? {
            ParamValue::Variant(variant) => Some(variant),
            ParamValue::Color(_) => None,
        }
    }

    /// All parameters, sorted by name.
    pub fn iter(&self) -> impl ExactSizeIterator<Item = (&str, &ParamValue)> {
        self.0.iter().map(|(name, value)| (name.as_str(), value))
    }

    /// Number of parameters.
    #[must_use]
    pub fn len(&self) -> usize {
        self.0.len()
    }

    /// True when no parameter is given.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.0.is_empty()
    }
}

impl<'de> Deserialize<'de> for ParamValue {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct ParamVisitor;

        impl Visitor<'_> for ParamVisitor {
            type Value = ParamValue;

            fn expecting(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
                f.write_str("a string: a colour like \"#a1b2c3\" or the name of a variant")
            }

            fn visit_str<E: de::Error>(self, value: &str) -> Result<ParamValue, E> {
                ParamValue::parse(value).ok_or_else(|| {
                    E::custom(format!(
                        "`{value}` is not a colour: colours have the form `#rrggbb` or `#rgb`"
                    ))
                })
            }
        }

        deserializer.deserialize_any(ParamVisitor)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Debug, Deserialize)]
    struct Holder {
        params: Params,
    }

    fn parse(text: &str) -> Result<Params, toml::de::Error> {
        toml::from_str::<Holder>(text).map(|holder| holder.params)
    }

    #[test]
    fn colours_and_variants_parse() {
        let params = parse(
            r##"
[params]
style = "scaly"
leaf = "#4C8a2e"
bark = "#f80"
"##,
        )
        .unwrap();
        assert_eq!(params.len(), 3);
        assert!(!params.is_empty());
        assert_eq!(params.color("leaf"), Some([0x4c, 0x8a, 0x2e]));
        assert_eq!(params.color("bark"), Some([0xff, 0x88, 0x00]));
        assert_eq!(params.variant("style"), Some("scaly"));
        assert_eq!(
            params.get("style"),
            Some(&ParamValue::Variant("scaly".to_owned()))
        );
        assert_eq!(
            params.get("leaf"),
            Some(&ParamValue::Color([0x4c, 0x8a, 0x2e]))
        );

        // The typed getters do not coerce, and a missing name has no value.
        assert_eq!(params.color("style"), None);
        assert_eq!(params.variant("leaf"), None);
        assert_eq!(params.get("missing"), None);
        assert_eq!(params.color("missing"), None);
        assert_eq!(params.variant("missing"), None);

        // Iteration is sorted by name whatever the order in the file.
        let names: Vec<&str> = params.iter().map(|(name, _)| name).collect();
        assert_eq!(names, ["bark", "leaf", "style"]);
    }

    #[test]
    fn empty_and_default() {
        assert!(parse("params = {}").unwrap().is_empty());
        assert_eq!(Params::default().len(), 0);
        assert_eq!(Params::default().iter().len(), 0);
    }

    #[test]
    fn colours_are_strict() {
        let color = |text: &str| ParamValue::parse(text);
        assert_eq!(color("#000000"), Some(ParamValue::Color([0, 0, 0])));
        assert_eq!(color("#FFfe01"), Some(ParamValue::Color([255, 254, 1])));
        assert_eq!(color("#fff"), Some(ParamValue::Color([255, 255, 255])));
        assert_eq!(color("#1aF"), Some(ParamValue::Color([0x11, 0xaa, 0xff])));
        for bad in [
            "#", "#1", "#12", "#1234", "#12345", "#1234567", "#12345g", "#+12345", "# 12345",
            "#-12", "#ééé", "#éé", "#ä1", "#12345é",
        ] {
            assert_eq!(color(bad), None, "{bad}");
            let error = parse(&format!("params = {{ c = \"{bad}\" }}")).unwrap_err();
            assert!(
                error.message().contains("`#rrggbb` or `#rgb`"),
                "{bad}: {}",
                error.message()
            );
        }
        // A string without `#` is a variant, whatever it looks like.
        assert_eq!(
            color("a1b2c3"),
            Some(ParamValue::Variant("a1b2c3".to_owned()))
        );
        assert_eq!(color(""), Some(ParamValue::Variant(String::new())));
        assert_eq!(
            parse(r#"params = { c = "a1b2c3" }"#).unwrap().variant("c"),
            Some("a1b2c3")
        );
    }

    #[test]
    fn only_strings_are_parameters() {
        for bad in ["3", "1.5", "true", "[1, 2]", "{ a = 1 }", "1979-05-27"] {
            let error = parse(&format!("params = {{ v = {bad} }}")).unwrap_err();
            assert!(
                error
                    .message()
                    .contains("expected a string: a colour like \"#a1b2c3\" or the name"),
                "{bad}: {}",
                error.message()
            );
        }
    }

    #[test]
    fn provenance_names() {
        #[derive(Deserialize)]
        struct P {
            provenance: Provenance,
        }
        let own: P = toml::from_str("provenance = \"own\"").unwrap();
        let placeholder: P = toml::from_str("provenance = \"placeholder\"").unwrap();
        assert_eq!(own.provenance, Provenance::Own);
        assert_eq!(placeholder.provenance, Provenance::Placeholder);
        assert!(toml::from_str::<P>("provenance = \"stolen\"").is_err());
    }
}
